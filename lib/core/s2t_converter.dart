  /// 完整简→繁映射（2743 对），从 assets/data/s2t_mapping.json 懒加载
  static Map<String, String>? _fullS2T;

  /// 加载完整繁简映射表（启动后调一次，后续直接用缓存）
  ///
  /// 必须在数据库初始化前调用：DB 迁移 v5→v6 依赖完整映射把历史繁体数据
  /// 转成简体，而迁移只跑一次——回退到内置的 270 对会永久残留繁体字。
  static Future<void> loadMappings() async {
    await Future.wait([
      _loadMap('assets/data/t2s_mapping.json').then((m) => _fullT2S = m),
      _loadMap('assets/data/s2t_mapping.json').then((m) => _fullS2T = m),
    ]);
  }

  /// 读取映射文件；失败时返回 null（调用方回退到内置映射）
  static Future<Map<String, String>?> _loadMap(String asset) async {
    try {
      final jsonStr = await rootBundle.loadString(asset);
      final raw = jsonDecode(jsonStr) as Map<String, dynamic>;
      return raw.map((k, v) => MapEntry(k, v as String));
    } catch (e) {
      debugPrint('⚠️ 加载 $asset 失败，回退到内置映射: $e');
      return null;
    }
  }

  /// 完整繁→简映射（未加载时回退到 s2t 的反向映射）
  static Map<String, String> get t2sMap => _fullT2S ?? t2s;

  /// 完整简→繁映射（未加载时回退到内置 s2t）
  static Map<String, String> get s2tMap => _fullS2T ?? s2t;

  /// 全局繁简偏好：true = 显示繁体，false = 显示简体。
  ///
  /// 由设置页的「繁体显示」开关驱动。模型层（Poem.fromMap 等）通过
  /// [apply] 读取它，使得首页 / 搜索 / 收藏 / 历史等未单独实现
  /// 繁简开关的页面也能跟随设置，避免只有部分页面变繁体的不一致。
  static bool preferTraditional = false;

  /// 从 SharedPreferences 同步繁简偏好（启动时、设置变更时调用）
  static Future<void> syncPreference() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      preferTraditional = prefs.getBool('traditional_chinese') ?? false;
    } catch (_) {
      // 读取失败保持默认简体
    }
  }

  /// 按当前偏好输出文本：开繁体则转繁体，否则转简体。
  ///
  /// 转简体用的是完整映射（3751 对），转繁体用的是 s2t（约 270 对）。
  /// 两者对已转换的文本都近似幂等，因此页面层再包一层 _t() 不会出错。
  static String apply(String text) =>
      preferTraditional ? toTraditional(text) : toSimplified(text);

  /// 简体 → 繁体（优先用完整映射，未命中则回退内置 s2t）
  static String toTraditional(String text) {
    if (text.isEmpty) return text;
    final map = s2tMap;
    final sb = StringBuffer();
    for (final char in text.runes) {
      final s = String.fromCharCode(char);
      sb.write(map[s] ?? s);
    }
    return sb.toString();
  }

  /// 繁体 → 简体（优先用完整映射，未命中则回退 s2t 反向映射）
  static String toSimplified(String text) {
    if (text.isEmpty) return text;
    final map = t2sMap;
    final sb = StringBuffer();
    for (final char in text.runes) {
      final s = String.fromCharCode(char);
      sb.write(map[s] ?? s);
    }
    return sb.toString();
  }
