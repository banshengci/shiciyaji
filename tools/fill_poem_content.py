def apply_content():
    """将内容应用到所有JSON文件"""
    files = [
        'assets/data/poems.json',
        'assets/data/poems_v2.json', 
        'assets/data/pack_tangshi.json',
        'assets/data/pack_songci.json',
        'assets/data/pack_xiaoxue.json'
    ]
    
    total_updated = 0
    
    for fpath in files:
        if not os.path.exists(fpath):
            continue
        with open(fpath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        updated = 0
        for p in data.get('poems', []):
            title = p.get('title', '')
            if title in CONTENT:
                c = CONTENT[title]
                if not p.get('translation') and c.get('translation'):
                    p['translation'] = c['translation']
                    updated += 1
                if not p.get('appreciation') and c.get('appreciation'):
                    p['appreciation'] = c['appreciation']
                if not p.get('background') and c.get('background'):
                    p['background'] = c['background']
        
        if updated > 0:
            with open(fpath, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
        
        total_updated += updated
        print(f'{fpath.split("/")[-1]}: 更新了 {updated} 首')
    
    print(f'\n总计更新: {total_updated} 首诗词')

if __name__ == '__main__':
    apply_content()
