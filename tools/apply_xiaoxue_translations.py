def main() -> None:
    data = json.loads(PACK.read_text(encoding="utf-8"))
    poems = data if isinstance(data, list) else data["poems"]
    index = {int(p["id"]): p for p in poems}
    hit = 0
    for pid, trans in TRANSLATIONS.items():
        p = index.get(pid)
        if not p:
            print("missing", pid)
            continue
        p["translation"] = trans
        hit += 1
        print("fixed", pid, p.get("title"))
    PACK.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"applied {hit} -> {PACK}")


if __name__ == "__main__":
    main()
