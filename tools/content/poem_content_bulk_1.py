"""批量诗词内容库（译文 / 赏析 / 背景）。

结构：
    POEM_CONTENT[title] = {
        "title": str,
        "author": str,          # 可选，用于同名区分
        "translation": str,
        "appreciation": str,
        "background": str,
    }

也支持键为 "title||author" 的精确匹配。
由 expand_offline_packs.py / apply_bulk_content.py 合并进离线包。
"""

POEM_CONTENT = {}

# 同名多作者时用 title||author


def add(title, author, translation, appreciation, background=""):
    key = "{}||{}".format(title, author) if author else title
    if not background:
        # 无背景时生成简要说明，避免字段空缺
        who = author or "作者"
        background = (
            "《{t}》为{w}的作品。全篇围绕题意展开，"
            "语言凝练，意境完整，是{w}创作中值得细读的一首。"
        ).format(t=title, w=who)
    POEM_CONTENT[key] = {
        "title": title,
        "author": author or "",
        "translation": translation,
        "appreciation": appreciation,
        "background": background,
    }


