def main() -> None:
    packs = {
        "tangshi.json": ROOT / "assets" / "data" / "packs" / "tangshi.json",
        "songci.json": ROOT / "assets" / "data" / "packs" / "songci.json",
    }
    data_map = {k: json.loads(p.read_text(encoding="utf-8")) for k, p in packs.items()}
    index = {}
    for name, data in data_map.items():
        poems = data if isinstance(data, list) else data["poems"]
        index[name] = {int(p["id"]): p for p in poems}
    hit = 0
    for (pack, pid), trans in T.items():
        p = index[pack].get(pid)
        if not p:
            print("MISSING", pack, pid)
            continue
        if (p.get("translation") or "").strip():
            print("SKIP", pid)
            continue
        p["translation"] = trans
        hit += 1
        print("fixed", pid, p.get("title"))
    for name, path in packs.items():
        path.write_text(json.dumps(data_map[name], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"applied {hit}/{len(T)}")


if __name__ == "__main__":
    main()
